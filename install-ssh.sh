#!/usr/bin/env bash
#
# install-ssh.sh
# Установка и базовая настройка OpenSSH-сервера на Ubuntu Server.
# Назначение: подготовить Linux-серверы стенда (SRV-LIN, SRV-MAIL-LIN, SRV-GW-LIN)
# к управлению по SSH с рабочей станции ADMIN-WS.
#
# Запуск (от имени локального администратора sysadmin):
#     sudo bash install-ssh.sh
#
# Скрипт идемпотентен: повторный запуск не дублирует настройки.
#
set -euo pipefail

# =====================================================================
# Настройки (при необходимости меняйте под свой стенд)
# =====================================================================
SSH_PORT=22                 # Порт SSH. Меняйте только осознанно, вместе с настройкой firewall.
PASSWORD_AUTH="yes"         # yes — вход по паролю (проще для учебного стенда).
                            # После настройки SSH-ключей можно выставить "no".
INSTALL_EXTRAS="yes"        # yes — дополнительно установить вспомогательные утилиты.
EXTRAS_PACKAGES=(curl git vim htop net-tools ca-certificates)

# =====================================================================
# Служебные функции
# =====================================================================
log()  { printf '\n\033[1;32m==> %s\033[0m\n' "$*"; }
warn() { printf '\n\033[1;33m[!] %s\033[0m\n' "$*"; }
fail() { printf '\n\033[1;31m[x] %s\033[0m\n' "$*"; exit 1; }

# =====================================================================
# 0. Права и окружение
# =====================================================================
if [[ ${EUID} -ne 0 ]]; then
  warn "Нужны права root. Повторяю запуск через sudo..."
  exec sudo bash "$0" "$@"
fi

if [[ ! -f /etc/os-release ]]; then
  fail "Не удалось определить ОС (нет /etc/os-release). Останавливаюсь."
fi
# shellcheck source=/dev/null
. /etc/os-release
log "Определена система: ${PRETTY_NAME:-${NAME} ${VERSION_ID}}"

# Скрипт рассчитан на Debian/Ubuntu (пакетный менеджер apt-get).
if ! command -v apt-get >/dev/null 2>&1; then
  fail "Скрипт предназначен для Debian/Ubuntu (apt-get не найден). Останавливаюсь."
fi

# =====================================================================
# 1. Обновление индекса пакетов
# =====================================================================
log "Обновляю список пакетов (apt-get update)..."
if ! apt-get update; then
  warn "apt-get update завершился с ошибкой. "
  warn "Если на этой ВМ нет выхода в Интернет, временно подключите "
  warn "VirtualBox NAT-адаптер (только для обновлений) и повторите запуск."
  fail "Не могу обновить список пакетов."
fi

# =====================================================================
# 2. Установка OpenSSH-сервера
# =====================================================================
log "Устанавливаю openssh-server..."
DEBIAN_FRONTEND=noninteractive apt-get install -y openssh-server

# =====================================================================
# 3. Включение и запуск службы
# =====================================================================
log "Включаю и запускаю службу ssh (автозапуск при загрузке)..."
systemctl enable --now ssh
systemctl --no-pager --full status ssh || true

# =====================================================================
# 4. Резервная копия и параметры конфигурации
# =====================================================================
SSHD_CONFIG="/etc/ssh/sshd_config"
SSHD_CONFD="/etc/ssh/sshd_config.d"
DROPIN="${SSHD_CONFD}/99-lab.conf"

if [[ ! -f "${SSHD_CONFIG}.orig" ]]; then
  cp -a "${SSHD_CONFIG}" "${SSHD_CONFIG}.orig"
  log "Создана резервная копия: ${SSHD_CONFIG}.orig"
else
  log "Резервная копия ${SSHD_CONFIG}.orig уже существует — не перезаписываю."
fi

if [[ -d "${SSHD_CONFD}" ]]; then
  log "Записываю параметры SSH в drop-in файл: ${DROPIN}"
  umask 077
  cat > "${DROPIN}" <<EOF
# Сгенерировано install-ssh.sh ($(date -u +%Y-%m-%dT%H:%M:%SZ)).
# Основной файл ${SSHD_CONFIG} не изменялся.
Port ${SSH_PORT}
PermitRootLogin prohibit-password
PasswordAuthentication ${PASSWORD_AUTH}
PubkeyAuthentication yes
EOF
else
  warn "Каталог ${SSHD_CONFD} отсутствует — вручную менять ${SSHD_CONFIG} не буду."
  warn "Проверьте сами, что в ${SSHD_CONFIG} разрешён вход по паролю (PasswordAuthentication yes)."
fi

# =====================================================================
# 5. Проверка конфигурации и перезапуск
# =====================================================================
log "Проверяю синтаксис конфигурации sshd..."
sshd -t
log "Перезапускаю службу ssh..."
systemctl restart ssh

# =====================================================================
# 6. Дополнительные утилиты (необязательно)
# =====================================================================
if [[ "${INSTALL_EXTRAS}" == "yes" ]]; then
  log "Устанавливаю вспомогательные утилиты: ${EXTRAS_PACKAGES[*]}"
  DEBIAN_FRONTEND=noninteractive apt-get install -y "${EXTRAS_PACKAGES[@]}"
fi

# =====================================================================
# 7. Firewall (только если ufw установлен)
# =====================================================================
if command -v ufw >/dev/null 2>&1; then
  log "Разрешаю SSH в ufw (правило добавляется, даже если ufw выключен)..."
  ufw allow "${SSH_PORT}/tcp" || warn "Не удалось добавить правило ufw — проверьте вручную."
fi

# =====================================================================
# 8. Итоговая информация
# =====================================================================
log "Готово. Служба SSH активна."
printf '\nСетевые интерфейсы (IPv4):\n'
ip -4 -brief address show || true

printf '\nПодключение с ADMIN-WS:\n'
printf '    ssh sysadmin@<IP-адрес-интерфейса-MGMT>\n\n'
printf 'Ожидаемые адреса MGMT в стенде:\n'
printf '    SRV-LIN       192.168.56.40\n'
printf '    SRV-MAIL-LIN  192.168.56.50\n'
printf '    SRV-GW-LIN    192.168.56.60\n'
printf 'Если IP отличается, проверьте настройку сетевого адаптера (Host-Only, MGMT).\n'
